"""Generate JSON Schema and OpenAPI from the source models/routes (single source of truth).

    python -m agentcrash.codegen          # rewrite schemas/domain.schema.json, schemas/openapi.json
    python -m agentcrash.codegen --check  # exit 1 if a committed file differs (drift)

The typed web client is generated from ``openapi.json`` in M6.
"""

import argparse
import json
import sys
from collections.abc import Callable
from pathlib import Path
from typing import cast

from agentcrash.api.app import Services, create_app
from agentcrash.domain.models import CompiledScenario, Manifest, RunCreate, Scenario
from agentcrash.domain.ports import Store
from agentcrash.domain.registry import Registry

MODELS = {m.__name__: m for m in (Scenario, CompiledScenario, RunCreate, Manifest)}
HEADER = (
    "GENERATED by `python -m agentcrash.codegen` from the source models and routes. "
    "Do not edit; change the source and regenerate."
)


def _dump(doc: object) -> str:
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_domain() -> str:
    schemas = {name: model.model_json_schema() for name, model in MODELS.items()}
    return _dump({"$comment": HEADER, "schemas": schemas})


def render_openapi() -> str:
    # Schema-only app: no store, no registry data, no token. Routes are never called.
    services = Services(
        store=cast(Store, None),
        registry=Registry(environments={}, graders={}, agents={}),
        token="",
        expected_revision="",
        provenance=lambda: (_ for _ in ()).throw(RuntimeError("schema generation only")),
    )
    spec = create_app(services).openapi()
    return _dump({**spec, "x-generated": HEADER})


OUTPUTS: dict[Path, Callable[[], str]] = {
    Path("schemas") / "domain.schema.json": render_domain,
    Path("schemas") / "openapi.json": render_openapi,
}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="agentcrash.codegen")
    parser.add_argument("--check", action="store_true", help="fail if generated output differs")
    parser.add_argument("--root", type=Path, default=Path("."), help="repository root")
    args = parser.parse_args(argv)
    drifted = False
    for relative, render in OUTPUTS.items():
        target = args.root / relative
        expected = render()
        if args.check:
            current = target.read_bytes().decode("utf-8") if target.exists() else None
            if current != expected:
                print(
                    f"{relative} is out of date; run `python -m agentcrash.codegen`",
                    file=sys.stderr,
                )
                drifted = True
            else:
                print(f"{relative} is up to date")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(expected.encode("utf-8"))  # bytes: keep LF on Windows
            print(f"wrote {relative}")
    return 1 if drifted else 0


# Kept for tests and callers that used the earlier single-file API.
OUTPUT = Path("schemas") / "domain.schema.json"
render = render_domain

if __name__ == "__main__":
    sys.exit(main())
